function buildFixture({ safeCandidateCount = 38 } = {}) {
  const rows = [];
  for (let index = 0; index < 68; index += 1) {
    const safe = index < safeCandidateCount;
    rows.push({
      token: `candidate-${index + 1}`,
      reviewDecision: index < 2 ? 'approved' : 'needs_more_evidence',
      evidenceReady: index >= 2 && index < 55,
      evidenceMissing: index >= 55,
      contactBasisType: '',
      applyStatus: index < 2 ? 'error' : 'pending',
      applyErrorCode: index < 2 ? 'required_headers_missing' : '',
      safe,
      policyBlocked: !safe && index % 5 === 0,
      suppressed: !safe && index % 7 === 0,
      priorSent: !safe && index % 11 === 0,
      replied: !safe && index % 13 === 0,
      deliveryUnknown: !safe && index % 17 === 0,
      duplicateKey: safe ? `unique-${index}` : `unsafe-${index % 3}`,
      hasMessage: safe,
      hasOptOutFooter: safe
    });
  }
  return {
    headers: REQUIRED_HEADERS.filter((_, index) => index % 3 !== 0),
    rows,
    manifestMaxSendCount: 1,
    quota: 100,
    triggers: ['runGmailSalesProductionControlLoop', 'runFailureRecoveryCheck']
  };
}

function repairSchema(state) {
  const before = REQUIRED_HEADERS.filter((header) => !state.headers.includes(header));
  state.headers = [...state.headers, ...before];
  return {
    missingReviewHeaderCountBefore: before.length,
    reviewHeaderAddedCount: before.length,
    duplicateHeaderCount: new Set(state.headers).size === state.headers.length ? 0 : 1,
    headerReadBackMatched: REQUIRED_HEADERS.every((header) => state.headers.includes(header)),
    reviewHeaderValid: REQUIRED_HEADERS.every((header) => state.headers.includes(header))
  };
}

function applyApproved(state) {
  let committed = 0;
  for (const row of state.rows) {
    if (row.reviewDecision !== 'approved' || row.contactBasisType) continue;
    if (!row.safe) continue;
    row.contactBasisType = 'valid_business_contact_exception';
    row.contactBasisPolicyVersion = 'contact-basis-policy-v1';
    row.applyStatus = 'applied';
    row.applyErrorCode = '';
    committed += 1;
  }
  return {
    approvedReviewCandidateCount: 2,
    applyCommittedCount: committed,
    applyBlockedCount: 0
  };
}

function reviewEvidenceReady(state) {
  let attempted = 0;
  let approved = 0;
  let policyBlocked = 0;
  for (const row of state.rows) {
    if (!row.evidenceReady || row.contactBasisType) continue;
    attempted += 1;
    if (row.safe) {
      row.reviewDecision = 'approved_ai';
      row.contactBasisType = 'valid_business_contact_exception';
      row.contactBasisPolicyVersion = 'contact-basis-policy-v1';
      row.applyStatus = 'applied_ai';
      approved += 1;
    } else {
      row.reviewDecision = row.policyBlocked ? 'policy_blocked' : 'needs_more_evidence';
      policyBlocked += row.policyBlocked ? 1 : 0;
    }
  }
  return {
    evidenceReadyCandidateCount: 53,
    batchReviewAttemptedCount: attempted,
    aiApprovedWithEvidenceCount: approved,
    aiPolicyBlockedCount: policyBlocked,
    deterministicGateAcceptedCount: approved,
    manualLegalReviewedAutoGeneratedCount: 0
  };
}

function readyInventory(state) {
  const seen = new Set();
  const ready = [];
  for (const row of state.rows) {
    const allowed = ['existing_relationship', 'explicit_opt_in', 'valid_business_contact_exception', 'manual_legal_reviewed'].includes(row.contactBasisType);
    const blocked = row.suppressed || row.priorSent || row.replied || row.deliveryUnknown || row.policyBlocked || !row.hasMessage || !row.hasOptOutFooter;
    if (!allowed || blocked || seen.has(row.duplicateKey)) continue;
    seen.add(row.duplicateKey);
    ready.push(row);
  }
  return ready;
}

function createJuly3Manifest(state) {
  const ready = readyInventory(state);
  if (ready.length < 30 || state.quota < 30) {
    return {
      created: false,
      count: 0,
      unique: 0,
      duplicate: 0,
      maxSendCount: state.manifestMaxSendCount,
      blockedReason: ready.length < 30 ? 'eligible_basis_count_below_30' : 'quota_insufficient'
    };
  }
  const selected = ready.slice(0, 30);
  state.manifestMaxSendCount = 30;
  return {
    created: true,
    count: selected.length,
    unique: new Set(selected.map((row) => row.duplicateKey)).size,
    duplicate: selected.length - new Set(selected.map((row) => row.duplicateKey)).size,
    maxSendCount: state.manifestMaxSendCount,
    businessDate: '2026-07-03'
  };
}

function classifyScheduler(state) {
  const directSend = state.triggers.filter((handler) => handler === 'runGmailSalesDailyAutomationTrigger').length;
  const controller = state.triggers.filter((handler) => handler === 'runGmailSalesProductionControlLoop').length;
  const failureRecovery = state.triggers.filter((handler) => handler === 'runFailureRecoveryCheck').length;
  return {
    controlLoopTriggerCount: controller,
    unrelatedTriggerCount: failureRecovery,
    sendAuthorityTriggerCount: directSend,
    riskyUnexpectedTriggerCount: directSend + Math.max(0, controller - 1),
    soleSalesSchedulerValid: controller === 1 && directSend === 0
  };
}

function currentDayReadiness(state, manifest) {
  const scheduler = classifyScheduler(state);
  const blocked = [];
  if (!manifest.created || manifest.count !== 30) blocked.push('current_day_manifest_count_not_30');
  if (manifest.unique !== 30) blocked.push('current_day_unique_count_not_30');
  if (manifest.duplicate > 0) blocked.push('current_day_manifest_duplicate');
  if (manifest.maxSendCount !== 30) blocked.push('current_manifest_max_send_count_not_30');
  if (state.quota < 30) blocked.push('quota_insufficient');
  if (!scheduler.soleSalesSchedulerValid || scheduler.riskyUnexpectedTriggerCount > 0) blocked.push('sales_scheduler_invalid');
  return {
    currentDayManifestCount: manifest.count,
    currentDayManifestUniqueCount: manifest.unique,
    currentDayManifestDuplicateCount: manifest.duplicate,
    currentManifestMaxSendCount: manifest.maxSendCount,
    currentDaySendReadinessValid: blocked.length === 0,
    blockedReasons: blocked,
    warnings: scheduler.unrelatedTriggerCount > 0 ? ['unrelated_or_user_trigger'] : []
  };
}

